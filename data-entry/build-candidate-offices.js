#!/usr/bin/env node
/**
 * CANDIDATE OFFICE HISTORY — CSV → TypeScript build script
 *
 *   1. data-entry/candidate_office_history.csv
 *      (state, party, name, wiki_title, tier, office, start, end, source)
 *      One row per elected/public office a candidate held, from the Wikipedia
 *      officeholder infobox of the article linked on their election page(s).
 *      tier: 5 U.S. Senate/Governor · 4 U.S. House/statewide · 3 state legislature ·
 *            2 local elected · 1 other public office · 0 article found, no office.
 *      A candidate with no article has one row with a blank tier (source "none").
 *   2. Run:  node data-entry/build-candidate-offices.js
 *   3. data/candidateOffices.ts is regenerated
 *
 * Feeds the Layer B observable prior on candidate effects (lib/tplCompute.ts
 * buildObservablePrior) and the forward backtest.
 */

const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "candidate_office_history.csv");
const OUT = path.join(__dirname, "../data/candidateOffices.ts");

function splitCSVLine(line) {
  const out = []; let cur = "", inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') { if (inQ && line[i + 1] === '"') { cur += '"'; i++; } else inQ = !inQ; }
    else if (ch === "," && !inQ) { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

// Same normalisation as warCandidateKey() in lib/tplCompute.ts.
const key = (state, party, name) => `${state}|${party}|${name.toLowerCase().replace(/[^a-z ]/g, "").replace(/\s+/g, " ").trim()}`;

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/).filter((l) => l.trim());
const header = splitCSVLine(lines[0]);
const col = (row, name) => row[header.indexOf(name)] ?? "";
const byKey = new Map();
let candidates = 0, withArticle = 0;
for (const line of lines.slice(1)) {
  const row = splitCSVLine(line);
  const k = key(col(row, "state"), col(row, "party"), col(row, "name"));
  if (!byKey.has(k)) { byKey.set(k, { title: col(row, "wiki_title") || null, offices: [] }); candidates++; if (col(row, "wiki_title")) withArticle++; }
  const tier = col(row, "tier");
  if (tier === "" || tier === "0") continue;
  const s = col(row, "start"), e = col(row, "end");
  byKey.get(k).offices.push({ t: Number(tier), s: s ? Number(s) : null, e: e ? Number(e) : null, o: col(row, "office") });
}

const entries = [...byKey.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
let ts = `// Auto-generated by data-entry/build-candidate-offices.js from data-entry/candidate_office_history.csv\n`;
ts += `// ${candidates} candidates, ${withArticle} with a Wikipedia article. Do not edit by hand.\n\n`;
ts += `export interface OfficeHeld { t: 1 | 2 | 3 | 4 | 5; s: number | null; e: number | null; o: string; }\n`;
ts += `export interface CandidateOfficeRecord { title: string | null; offices: OfficeHeld[]; }\n\n`;
ts += `export const candidateOffices: Record<string, CandidateOfficeRecord> = {\n`;
for (const [k, v] of entries) ts += `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
ts += `};\n`;
fs.writeFileSync(OUT, ts);
console.log(`Wrote ${OUT}: ${candidates} candidates, ${withArticle} with article, ${entries.reduce((n, [, v]) => n + v.offices.length, 0)} office rows`);
