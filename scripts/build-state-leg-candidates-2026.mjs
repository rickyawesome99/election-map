#!/usr/bin/env node
/**
 * Regenerates data/stateLegCandidates2026.ts from data-entry/state-leg-candidates-2026/{ABBR}.json -
 * the 2026 general-election candidates for every state legislative district on the ballot,
 * fetched from Ballotpedia's chamber election pages by scripts/fetch-state-leg-candidates-2026.py.
 *
 * Usage: node scripts/build-state-leg-candidates-2026.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";

const SRC_DIR = "data-entry/state-leg-candidates-2026";
const OUT_FILE = "data/stateLegCandidates2026.ts";

const files = existsSync(SRC_DIR) ? readdirSync(SRC_DIR).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort() : [];
const data = {};
let districts = 0, candidates = 0, fetched = "";
for (const file of files) {
  const abbr = file.replace(/\.json$/, "");
  const parsed = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
  fetched = parsed.meta?.fetched ?? fetched;
  const out = {};
  for (const chamber of ["house", "senate"]) {
    if (!parsed[chamber]) continue;
    out[chamber] = parsed[chamber];
    for (const d of Object.values(parsed[chamber])) { districts += 1; candidates += d.candidates.length; }
  }
  if (Object.keys(out).length) data[abbr] = out;
}

const header = `import type { Chamber } from "./stateLegDistricts";

// 2026 general-election candidates for every state legislative district on the ballot, from
// Ballotpedia's chamber election pages ("<State> House of Representatives elections, 2026" and
// the Senate / Assembly / House of Delegates variants), fetched ${fetched}. Auto-generated by
// scripts/build-state-leg-candidates-2026.mjs from data-entry/state-leg-candidates-2026/{ABBR}.json;
// refresh with scripts/fetch-state-leg-candidates-2026.py (clear its HTML cache first). Do not
// edit by hand. A chamber not on the 2026 ballot is absent.
//
// Ballotpedia's own caveat applies: "The candidate list in this election may not be complete."
// Write-in candidates are kept and flagged; \`seats\` is set only where the page marks a
// multi-member district.

export type StateLegCandidate2026 = {
  name: string;
  party: "D" | "R" | "O";
  /** Ballotpedia's party label for a non-major candidate ("Libertarian Party", "Independent"). */
  partyLabel?: string;
  incumbent?: boolean;
  writeIn?: boolean;
  /** Idaho's seat A/B and Washington's position 1/2: the separate race within the district. */
  post?: string;
  /** The general was canceled (Oklahoma: a sole filer is elected without a vote); this is that filer, or the party's filers. */
  canceledGeneral?: boolean;
};

export type StateLegDistrictCandidates2026 = { candidates: StateLegCandidate2026[]; seats?: number };

export const stateLegCandidates2026Fetched = ${JSON.stringify(fetched)};

// state abbreviation -> chamber -> district key
export const stateLegCandidates2026: Record<string, Partial<Record<Chamber, Record<string, StateLegDistrictCandidates2026>>>> = `;

writeFileSync(OUT_FILE, `${header}${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${OUT_FILE}: ${Object.keys(data).length} states, ${districts} districts, ${candidates} candidates`);
