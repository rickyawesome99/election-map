#!/usr/bin/env node
/**
 * Regenerates data/stateLegOutgoing2026.ts from data-entry/state-leg-outgoing-2026/{ABBR}.json
 * (scripts/fetch-state-leg-outgoing-2026.py: the Wikipedia chamber articles' outgoing-incumbent
 * sections). A "?" party in the source is filled from the roster's sitting member of that district
 * with the same name, the way the articles themselves identify the person.
 *
 * Usage: node scripts/build-state-leg-outgoing-2026.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";

const SRC_DIR = "data-entry/state-leg-outgoing-2026";
const OUT_FILE = "data/stateLegOutgoing2026.ts";

const rosterSrc = readFileSync("data/stateLegDistricts.ts", "utf8");
const rosterBody = rosterSrc.slice(rosterSrc.indexOf("{", rosterSrc.indexOf("export const stateLegDistricts")));
const roster = JSON.parse(rosterBody.slice(0, rosterBody.lastIndexOf("}") + 1));

const norm = (s) => s.normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/\(.*?\)|".*?"/g, " ").replace(/[^a-z\s]/g, " ").split(/\s+/).filter((t) => t && !["jr", "sr", "ii", "iii", "iv"].includes(t));
const loose = (s) => { const t = norm(s); return t.length ? `${t[0]} ${t[t.length - 1]}` : ""; };

const files = existsSync(SRC_DIR) ? readdirSync(SRC_DIR).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort() : [];
const data = {};
let people = 0, districts = 0, chambers = 0, filled = 0, unknown = 0;
let fetched = "";
for (const file of files) {
  const abbr = file.replace(/\.json$/, "");
  const parsed = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
  fetched = parsed.meta?.fetched ?? fetched;
  const out = {};
  for (const chamber of ["house", "senate"]) {
    const block = parsed[chamber];
    if (!block || Object.keys(block).length === 0) continue;
    chambers += 1;
    out[chamber] = {};
    for (const [key, entries] of Object.entries(block)) {
      const district = roster[abbr]?.[chamber]?.find((d) => d.number === key);
      out[chamber][key] = entries.map((e) => {
        const entry = { name: e.name, party: e.party, category: e.category, reason: e.reason };
        if (e.post) entry.post = e.post;
        if (entry.party === "?") {
          const inc = (district?.incumbents ?? []).find((i) => loose(i.name) === loose(e.name));
          if (inc) { entry.party = inc.party === "I" ? "O" : inc.party; filled += 1; } else { entry.party = "O"; unknown += 1; }
        }
        people += 1;
        return entry;
      });
      districts += 1;
    }
  }
  if (Object.keys(out).length) data[abbr] = out;
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Outgoing incumbents of the 2026 state legislative elections, with reasons: members not seeking
// re-election to their seat (term-limited, retiring, running for another office, resigned, lost
// renomination), from the English Wikipedia chamber election articles' retirement sections
// (scripts/fetch-state-leg-outgoing-2026.py → data-entry/state-leg-outgoing-2026/{ABBR}.json),
// fetched ${fetched}. Auto-generated by scripts/build-state-leg-outgoing-2026.mjs; do not edit by hand.
//
// Coverage follows the articles: a chamber with no retirement section (North Dakota, West Virginia
// Senate, Pennsylvania Senate, Nevada Senate, New Hampshire Senate) is absent, and the lists lag
// the ballot. The Ballotpedia field (data/stateLegCandidates2026.ts) remains the authority on who
// IS running; this says why a seat is open.

export type StateLegOutgoingCategory = "term-limited" | "retiring" | "running for other office" | "resigned" | "lost primary" | "disqualified" | "not running";

export type StateLegOutgoing2026 = {
  name: string;
  party: "D" | "R" | "O";
  category: StateLegOutgoingCategory;
  /** The article's phrasing, trimmed: "term-limited", "retiring to run for State Senate". */
  reason: string;
  /** Idaho's seat A/B, Washington's position 1/2. */
  post?: string;
};

export const stateLegOutgoing2026Fetched = ${JSON.stringify(fetched)};

// state abbreviation -> chamber -> district key
export const stateLegOutgoing2026: Record<string, Partial<Record<Chamber, Record<string, StateLegOutgoing2026[]>>>> = `;

writeFileSync(OUT_FILE, `${header}${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${OUT_FILE}: ${Object.keys(data).length} states, ${chambers} chambers, ${districts} districts, ${people} outgoing members (${filled} parties filled from the roster, ${unknown} unknown → O)`);
