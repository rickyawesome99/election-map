#!/usr/bin/env node
/**
 * Regenerates data/stateLegRedistricting.ts from data-entry/state-leg-redistricting/{ABBR}.json -
 * the per-district redistricting history (what each district is made of in terms of the previous
 * map's districts, counties gained and lost, the 2020 presidential shift, and a generated
 * description) built by scripts/build-state-leg-redistricting.py.
 *
 * The `contributors` arrays are also the population-weighted old-to-new crosswalk the 2026
 * projection uses to relocate pre-redraw results onto today's lines.
 *
 * Usage: node scripts/build-state-leg-redistricting.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";

const SRC_DIR = "data-entry/state-leg-redistricting";
const OUT_FILE = "data/stateLegRedistricting.ts";

const files = existsSync(SRC_DIR) ? readdirSync(SRC_DIR).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort() : [];
const data = {};
let transitions = 0;
let districts = 0;
for (const file of files) {
  const abbr = file.replace(/\.json$/, "");
  const parsed = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
  const out = {};
  for (const chamber of ["house", "senate"]) {
    if (!parsed[chamber]) continue;
    out[chamber] = parsed[chamber];
    for (const block of Object.values(parsed[chamber])) {
      transitions += 1;
      districts += Object.keys(block).length;
    }
  }
  if (Object.keys(out).length) data[abbr] = out;
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Per-district redistricting history for every state legislative chamber, one record per district
// per map transition: what the NEW district is made of in terms of the previous map's districts
// (population-weighted, from Dave's Redistricting 2020-VTD populations area-apportioned onto the
// intersection of the two maps), the counties it gained and lost, and its 2020 presidential margin
// on both sets of lines. Auto-generated by scripts/build-state-leg-redistricting.mjs from
// data-entry/state-leg-redistricting/{ABBR}.json (scripts/build-state-leg-redistricting.py).
// Do not edit by hand.
//
// SERVER-ONLY: several megabytes. Pages read per-chamber slices.
//
// Keyed state -> chamber -> the era the district was redrawn INTO ("current" or the superseded
// boundary vintage from data/stateLegHistoricalMaps.ts) -> district key. \`contributors\` is the
// crosswalk the 2026 projection uses to relocate pre-redraw results onto today's lines.

export type RedistrictingContributor = { key: string; popPct: number; areaPct: number };
export type RedistrictingCounty = { county: string; popPct: number };

export type StateLegRedistrictingEntry = {
  fromEra: string;
  toEra: string;
  /** Share of the new district's population that lived in the same-keyed district of the previous map. */
  retainedPopPct: number;
  retainedAreaPct: number;
  pop2020: number;
  /** Previous-map districts the new one draws from, population shares descending (>= 0.5%). */
  contributors: RedistrictingContributor[];
  /** County composition of the new district, population shares (>= 0.5%). */
  counties: RedistrictingCounty[];
  countiesGained: RedistrictingCounty[];
  countiesLost: RedistrictingCounty[];
  /** 2020 presidential margin (R-positive) of the same-keyed district on the previous map, if it existed. */
  pres2020Old: number | null;
  pres2020New: number | null;
  /** Generated description: geography first, then the presidential shift. */
  text: string;
};

export type StateLegRedistricting = Record<string, Record<string, StateLegRedistrictingEntry>>;

export const stateLegRedistricting: Record<string, Partial<Record<Chamber, StateLegRedistricting>>> = `;

writeFileSync(OUT_FILE, `${header}${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${OUT_FILE}: ${Object.keys(data).length} states, ${transitions} chamber-transitions, ${districts} district-transitions`);
