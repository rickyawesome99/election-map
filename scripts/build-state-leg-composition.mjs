#!/usr/bin/env node
/**
 * Regenerates data/stateLegComposition.ts — every chamber's seats today (D, R, each other party,
 * vacancies) — from data-entry/state-leg-composition/ballotpedia-YYYY-MM.csv (the newest), a
 * capture of each Ballotpedia chamber page's "Partisan composition" box, plus the corrections in
 * ADJUST below. This is the "Now" on /legislatures and the chamber pages' "Current"; the
 * after-the-election counts stay in stateLegData.
 *
 * Usage: node scripts/build-state-leg-composition.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";

const DIR = "data-entry/state-leg-composition";
const OUT = "data/stateLegComposition.ts";

// Where our own sources say otherwise, with the reason. Applied on top of the capture.
const ADJUST = {
  // legislature.vermont.gov labels Joseph Parsons (Orange-Caledonia) Independent; Ballotpedia still R.
  "VT|house": { rep: -1, other: { Independent: +1 }, why: "Joseph Parsons is Independent on legislature.vermont.gov (Ballotpedia: R)" },
  // Nebraska by caucus, as the 2026 candidates are (data-entry/state-leg-party-overrides/ne_senate.json):
  // Victor Rountree, registered nonpartisan, sits with the Democrats; Megan Hunt stays independent.
  "NE|senate": { dem: +1, other: { Nonpartisan: -1 }, why: "Victor Rountree counted with the Democrats he caucuses with" },
};

const file = readdirSync(DIR).filter((f) => /^ballotpedia-\d{4}-\d{2}\.csv$/.test(f)).sort().at(-1);
const asOf = file.match(/(\d{4}-\d{2})/)[1];

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (q) { if (ch === '"' && text[i + 1] === '"') { cell += '"'; i += 1; } else if (ch === '"') q = false; else cell += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") { if (ch === "\r" && text[i + 1] === "\n") i += 1; row.push(cell); rows.push(row); row = []; cell = ""; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows.filter((r) => r.some((c) => c.trim()));
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? "").trim()])));
}

const out = {};
for (const r of parseCsv(readFileSync(`${DIR}/${file}`, "utf8"))) {
  const other = {};
  for (const part of r.other_detail.split(";").filter(Boolean)) {
    const [label, n] = part.split(":");
    other[label] = Number(n);
  }
  let dem = Number(r.dem), rep = Number(r.rep);
  const adj = ADJUST[`${r.state}|${r.chamber}`];
  if (adj) {
    dem += adj.dem ?? 0; rep += adj.rep ?? 0;
    for (const [label, d] of Object.entries(adj.other ?? {})) { other[label] = (other[label] ?? 0) + d; if (!other[label]) delete other[label]; }
  }
  const oth = Object.values(other).reduce((a, b) => a + b, 0);
  const vacant = Number(r.vacant), total = Number(r.total);
  if (dem + rep + oth + vacant !== total) throw new Error(`${r.state} ${r.chamber}: ${dem}+${rep}+${oth}+${vacant} != ${total}`);
  (out[r.state] ??= {})[r.chamber] = { dem, rep, oth, other, vacant, total };
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Every state legislative chamber's seats today: Democrats, Republicans, each other party by its
// own label (independents, Vermont Progressives, Utah's Forward, Alaska's nonpartisans), and
// vacancies. Auto-generated by scripts/build-state-leg-composition.mjs from
// ${DIR}/${file} (each Ballotpedia chamber page's "Partisan composition" box, as of ${asOf})
// with these corrections:
${Object.entries(ADJUST).map(([k, a]) => `//   ${k.replace("|", " ")}: ${a.why}`).join("\n")}
// Do not edit by hand. Nebraska's single chamber is under "senate".

export type ChamberComposition = { dem: number; rep: number; oth: number; other: Record<string, number>; vacant: number; total: number };

export const stateLegCompositionAsOf = ${JSON.stringify(asOf)};

export const stateLegComposition: Record<string, Partial<Record<Chamber, ChamberComposition>>> = `;
writeFileSync(OUT, `${header}${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${OUT}: ${Object.values(out).reduce((n, s) => n + Object.keys(s).length, 0)} chambers as of ${asOf}`);
