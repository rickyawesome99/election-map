#!/usr/bin/env python3
"""
Generates data/countyDemographics.ts from data-entry/county_acs_2020_24.csv (fetched by
scripts/fetch-acs-county-demographics.py): ACS 2020-24 5-year estimates, the same release and
variables as the state and district figures (data/demographics.ts), so counties and districts
share one source.

Two geographies the ACS no longer reports are rebuilt from the pieces it does:
- Connecticut's 8 legacy counties (09001-09015; the ACS reports CT's 9 planning regions since
  2022) from their own towns, through data-entry/ct_town_to_planning_region.csv.
- Alaska's Valdez-Cordova (02261, split into Chugach 02063 and Copper River 02066 in 2019) from
  those two areas.
Population is summed; shares and median income are population-weighted averages of the pieces
(an approximation for the median, which cannot be recombined exactly).
Run from project root: python3 scripts/generate-county-demographics-data.py
"""
import csv, os

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "data-entry/county_acs_2020_24.csv")
CT_CROSSWALK_SRC = os.path.join(ROOT, "data-entry/ct_town_to_planning_region.csv")
DST = os.path.join(ROOT, "data/countyDemographics.ts")

PCT_FIELDS = ["college_pct", "white_pct", "black_pct", "hispanic_pct", "asian_pct"]


def read_rows():
    counties, towns = {}, {}
    with open(SRC, newline="") as f:
        for row in csv.DictReader(f):
            rec = {k: (float(row[k]) if row[k] != "" else None) for k in ["population", "median_household_income", *PCT_FIELDS]}
            (counties if row["level"] == "county" else towns)[row["geoid"]] = rec
    return counties, towns


def combine(parts):
    """Sum population; population-weight everything else."""
    parts = [p for p in parts if p.get("population")]
    if not parts:
        return None
    out = {"population": sum(p["population"] for p in parts)}
    for k in ["median_household_income", *PCT_FIELDS]:
        usable = [(p[k], p["population"]) for p in parts if p[k] is not None]
        w = sum(pop for _, pop in usable)
        out[k] = sum(v * pop for v, pop in usable) / w if w else None
    return out


counties, towns = read_rows()

# Alaska's Valdez-Cordova.
if "02261" not in counties and "02063" in counties and "02066" in counties:
    counties["02261"] = combine([counties["02063"], counties["02066"]])

# Connecticut's legacy counties, from their towns. Town geoids in the ACS are state + planning
# region + county subdivision; the crosswalk maps each 2022 town code to its 2020 (legacy) county.
legacy_towns = {}
with open(CT_CROSSWALK_SRC, newline="", encoding="utf-8-sig") as f:
    for row in csv.DictReader(f):
        old_county = row["town_fips_2020"].zfill(10)[2:5]
        legacy_towns.setdefault(f"09{old_county}", []).append("09" + row["town_fips_2022"].zfill(10)[2:10])
for fips, geoids in legacy_towns.items():
    found = [towns[g] for g in geoids if g in towns]
    missing = [g for g in geoids if g not in towns]
    if missing:
        raise SystemExit(f"{fips}: towns missing from the ACS pull: {missing}")
    counties[fips] = combine(found)

out = [
    "// Auto-generated by scripts/generate-county-demographics-data.py from",
    "// data-entry/county_acs_2020_24.csv (scripts/fetch-acs-county-demographics.py): ACS 2020-24",
    "// 5-year estimates, the same release and variables as data/demographics.ts (states and",
    "// districts). Key = 5-digit county FIPS. Fields are omitted (not zero) where the ACS has no",
    "// value. CT's 8 legacy counties are rebuilt from their towns and AK's Valdez-Cordova (02261)",
    "// from Chugach + Copper River: population summed, the rest population-weighted.",
    "",
    "export type CountyDemographics = {",
    "  population?: number; // total population",
    "  collegePct?: number; // % of adults 25+ with a bachelor's degree or higher",
    "  whitePct?: number; // % White alone, not Hispanic or Latino",
    "  blackPct?: number; // % Black or African American alone, not Hispanic or Latino",
    "  hispanicPct?: number; // % Hispanic or Latino (any race)",
    "  asianPct?: number; // % Asian alone, not Hispanic or Latino",
    "  medianHouseholdIncome?: number; // dollars",
    "};",
    "",
    "export const countyDemographics: Record<string, CountyDemographics> = {",
]

KEYS = [("population", "population", 0), ("collegePct", "college_pct", 1), ("whitePct", "white_pct", 1),
        ("blackPct", "black_pct", 1), ("hispanicPct", "hispanic_pct", 1), ("asianPct", "asian_pct", 1),
        ("medianHouseholdIncome", "median_household_income", 0)]
n = 0
for fips in sorted(counties):
    rec = counties[fips]
    if not rec:
        continue
    fields = []
    for ts_key, col, digits in KEYS:
        v = rec.get(col)
        if v is None:
            continue
        fields.append(f"{ts_key}: {int(round(v)) if digits == 0 else round(v, 1)}")
    if fields:
        out.append(f'  "{fips}": {{ {", ".join(fields)} }},')
        n += 1

out += ["};", ""]
with open(DST, "w") as f:
    f.write("\n".join(out))
print(f"Written {n} counties -> {DST}")
