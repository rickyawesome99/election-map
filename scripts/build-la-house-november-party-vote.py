#!/usr/bin/env python3
"""
Louisiana U.S. House, November all-party primary: every Democratic candidate's votes and every
Republican candidate's votes summed per district, 2016-2024, from the Secretary of State's results
workbooks cached in data-entry/la-sos-results/ (downloaded by fetch-house-district-county-louisiana.py).

WHY. Until 2026 Louisiana's November House election was an all-party primary: several candidates of
one party could share the ballot, and house_past_results.csv keeps only the top candidate of each
party (or the December runoff). The adjusted House vote and the State TPL House row want the party
split of the November electorate instead (user decision 2026-11-24), so they read this file.
A seat decided without an election (LA-04 2022, one candidate filed) has no row.

Writes data-entry/la_house_november_party_vote.csv and data/laHouseNovemberPartyVote.ts.
Run from project root:  python3 scripts/build-la-house-november-party-vote.py
"""
import csv, json, os, re
import openpyxl

ROOT = os.path.join(os.path.dirname(__file__), "..")
CACHE = os.path.join(ROOT, "data-entry/la-sos-results")
NOVEMBER = {2016: "20161108.xlsx", 2018: "20181106.xlsx", 2020: "20201103.xlsx", 2022: "20221108.xlsx", 2024: "../la_2024_official_results.xlsx"}
PARTY_RE = re.compile(r"\(([A-Z/]+)\)\s*$")


def parse(path, year):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    sheet = next(n for n in wb.sheetnames if "Multi-Parish" in n and "Parish)" in n)
    rows = list(wb[sheet].iter_rows(values_only=True))
    starts = [i for i, r in enumerate(rows) if r and r[0] and "Congress" in str(r[0])] + [len(rows)]
    out = []
    for si in range(len(starts) - 1):
        m = re.search(r"(\d+)(?:st|nd|rd|th) Congressional District", str(rows[starts[si]][0]))
        if not m:
            continue
        names = [str(c).strip() for c in rows[starts[si] + 1][1:] if c]
        parties = [(PARTY_RE.search(n).group(1) if PARTY_RE.search(n) else "?") for n in names]
        votes = [0] * len(names)
        for r in rows[starts[si] + 3: starts[si + 1]]:
            if not r or r[0] is None:
                break
            if "total" in str(r[0]).lower():
                continue
            for i, v in enumerate(r[1:1 + len(names)]):
                votes[i] += int(v or 0)
        d = sum(v for v, p in zip(votes, parties) if p == "DEM")
        g = sum(v for v, p in zip(votes, parties) if p == "REP")
        n = int(m.group(1))
        out.append(dict(year=year, district_id=2200 + n, district_name=f"LA-{n:02d}", dem_votes=d, rep_votes=g, total_votes=sum(votes),
                        dem_candidates=parties.count("DEM"), rep_candidates=parties.count("REP"), other_candidates=len(parties) - parties.count("DEM") - parties.count("REP")))
    return out


def main():
    rows = []
    for year, f in NOVEMBER.items():
        rows += parse(os.path.normpath(os.path.join(CACHE, f)), year)
    rows.sort(key=lambda r: (r["year"], r["district_id"]))
    with open(os.path.join(ROOT, "data-entry/la_house_november_party_vote.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    body = ",\n".join("  " + json.dumps({"year": r["year"], "district": r["district_name"], "dem": r["dem_votes"], "rep": r["rep_votes"], "total": r["total_votes"], "demCandidates": r["dem_candidates"], "repCandidates": r["rep_candidates"]}) for r in rows)
    with open(os.path.join(ROOT, "data/laHouseNovemberPartyVote.ts"), "w") as f:
        f.write("// GENERATED by scripts/build-la-house-november-party-vote.py from the Louisiana Secretary of State's\n// November results workbooks. Do not edit by hand.\n"
                "export interface LaNovemberPartyVote { year: number; district: string; dem: number; rep: number; total: number; demCandidates: number; repCandidates: number }\n"
                f"export const laHouseNovemberPartyVote: LaNovemberPartyVote[] = [\n{body},\n];\n")
    for r in rows:
        t = r["total_votes"]
        print(f'{r["year"]} {r["district_name"]} D {r["dem_votes"]:>7} ({r["dem_candidates"]}) R {r["rep_votes"]:>7} ({r["rep_candidates"]}) other {r["other_candidates"]} total {t:>7}  R{(r["rep_votes"] - r["dem_votes"]) / t * 100:+.1f}')


if __name__ == "__main__":
    main()
