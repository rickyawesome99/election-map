#!/usr/bin/env node
/**
 * Regenerates data/stateLegPres2024.ts from data-entry/state-leg-pres2024/{ABBR}.json - the raw
 * per-district crosswalk output written by scripts/crosswalk-state-leg-pres2024.py (2024
 * presidential votes apportioned to state legislative districts via MEDSL's per-state 2024
 * precinct-level returns, see that script's docstring for the method).
 *
 * Only states with a data-entry/state-leg-pres2024/{ABBR}.json file are included; states/chambers
 * not yet sourced are simply absent (map/table already handle that gracefully). A chamber's JSON
 * can itself be a partial district list (e.g. a staggered Senate where only the districts up for
 * election in Nov 2024 have a same-year precinct row to crosswalk against) - those specific
 * districts are correspondingly absent until a supplementary source fills them in.
 *
 * Usage: node scripts/build-state-leg-pres2024.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from "fs";

const SRC_DIR = "data-entry/state-leg-pres2024";
const OUT_FILE = "data/stateLegPres2024.ts";

const files = readdirSync(SRC_DIR).filter((f) => f.endsWith(".json")).sort();

const data = {};
for (const file of files) {
  const abbr = file.replace(/\.json$/, "");
  data[abbr] = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Per-district 2024 presidential election results, reaggregated to each state's CURRENT
// (2026-effective) legislative district lines. Auto-generated by
// scripts/build-state-leg-pres2024.mjs from data-entry/state-leg-pres2024/*.json - do not edit by
// hand, rerun the build script instead. States/chambers not yet covered are simply absent, same
// convention as data/stateLegDistricts.ts. A partially-covered chamber (e.g. a staggered Senate
// where only half the districts had a Nov 2024 election to crosswalk against) is a JSON object
// missing those specific district keys, not a bug.

// Whether the district map colors by current seat-holder party or by 2024 presidential margin.
export type MapViewMode = "seats" | "president";

export type StateLegPres2024 = {
  demPct: number;
  repPct: number;
  margin: number;              // + = R advantage, - = D advantage (matches lib/colorScale.ts)
  demVotes?: number | null;
  repVotes?: number | null;
  totalVotes?: number | null;
  // true for a district with no Nov 2024 election of its own to crosswalk against (the
  // off-cycle half of a staggered Senate) - estimated instead via area-weighted overlay of the
  // current House districts' (precinct-exact) results onto the current Senate boundary, per
  // scripts/fill-state-leg-pres2024-gaps.py. Absent/false = precinct-exact.
  estimated?: boolean;
};

// Keyed by state abbreviation -> chamber -> district "number" field (the same key
// StateLegDistrict.number/the boundary file's extracted district code uses, e.g. "12", "12A").
export const stateLegPres2024: Record<string, Partial<Record<Chamber, Record<string, StateLegPres2024>>>> = `;

writeFileSync(OUT_FILE, header + JSON.stringify(data, null, 2) + ";\n");
console.log(`${OUT_FILE}: wrote ${files.length} states (${files.map((f) => f.replace(/\.json$/, "")).join(", ")})`);
