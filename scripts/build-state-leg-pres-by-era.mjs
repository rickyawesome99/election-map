#!/usr/bin/env node
/**
 * Regenerates data/stateLegPresByEra.ts from data-entry/state-leg-pres-by-era/{ABBR}.json - the
 * 2016/2020/2024 presidential vote inside every state legislative district on EVERY map era's
 * lines (built by scripts/build-state-leg-pres-by-era.py from Dave's Redistricting VTD data).
 *
 * This is the Legislative District Atlas's keystone table: the district pages show a seat's
 * presidential vote on the lines it was run on, the corrected chamber margin imputes unopposed
 * seats from it, and the 2026 projection crosswalks old-era results through it.
 *
 * Usage: node scripts/build-state-leg-pres-by-era.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";

const SRC_DIR = "data-entry/state-leg-pres-by-era";
const OUT_FILE = "data/stateLegPresByEra.ts";

const files = existsSync(SRC_DIR) ? readdirSync(SRC_DIR).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort() : [];

// The roster, for the overlay districts that have no polygon of their own: New Hampshire's 39 House
// floterials sit on listed base districts (`components`), so their presidential vote on the
// current map is the sum of those districts' votes. Nothing in the boundary files can place them
// on a superseded map, so only the current era is recombined.
const rosterSrc = readFileSync("data/stateLegDistricts.ts", "utf8");
const rosterBody = rosterSrc.slice(rosterSrc.indexOf("{", rosterSrc.indexOf("export const stateLegDistricts")));
const roster = JSON.parse(rosterBody.slice(0, rosterBody.lastIndexOf("}") + 1));

function recombineOverlays(abbr, chamber, era) {
  const districts = roster[abbr]?.[chamber] ?? [];
  let n = 0;
  for (const d of districts) {
    if (!d.overlay || !d.components?.length || era[d.number]) continue;
    const parts = d.components.map((k) => era[k]).filter(Boolean);
    if (parts.length !== d.components.length) continue;
    const rec = { pop2020: 0, splitPct: 0, overlayOf: d.components };
    for (const p of parts) { rec.pop2020 += p.pop2020 ?? 0; rec.splitPct = Math.max(rec.splitPct, p.splitPct ?? 0); }
    for (const y of ["2016", "2020", "2024"]) {
      if (!parts.every((p) => p[y])) continue;
      const v = { demVotes: 0, repVotes: 0, othVotes: 0, totalVotes: 0 };
      for (const p of parts) { v.demVotes += p[y].demVotes; v.repVotes += p[y].repVotes; v.othVotes += p[y].othVotes; v.totalVotes += p[y].totalVotes; }
      if (v.totalVotes === 0) continue;
      rec[y] = { ...v, demPct: +((100 * v.demVotes) / v.totalVotes).toFixed(1), repPct: +((100 * v.repVotes) / v.totalVotes).toFixed(1), margin: +((100 * (v.repVotes - v.demVotes)) / v.totalVotes).toFixed(1) };
    }
    era[d.number] = rec;
    n += 1;
  }
  return n;
}

const data = {};
let eras = 0;
let districts = 0;
let overlays = 0;
for (const file of files) {
  const abbr = file.replace(/\.json$/, "");
  const parsed = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
  const out = {};
  for (const chamber of ["house", "senate"]) {
    if (!parsed[chamber]) continue;
    if (parsed[chamber].current) overlays += recombineOverlays(abbr, chamber, parsed[chamber].current);
    out[chamber] = parsed[chamber];
    for (const block of Object.values(parsed[chamber])) {
      eras += 1;
      districts += Object.keys(block).length;
    }
  }
  if (Object.keys(out).length) data[abbr] = out;
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Presidential votes (2016, 2020, 2024) inside every state legislative district, on the lines of
// EVERY map era - the current map ("current") and each superseded era, keyed by the vintage used
// in data/stateLegHistoricalMaps.ts. Auto-generated by scripts/build-state-leg-pres-by-era.mjs
// from data-entry/state-leg-pres-by-era/{ABBR}.json; those come from
// scripts/build-state-leg-pres-by-era.py (Dave's Redistricting 2020-VTD election data,
// area-apportioned onto each era's district polygons). Do not edit by hand.
//
// SERVER-ONLY: this module is several megabytes. Pages read per-chamber slices instead.
//
// The 2024 figure on the CURRENT map is also in data/stateLegPres2024.ts, precinct-exact; keep
// using that one for display. This table's 2024-on-current cell exists so the overlay's error can
// be measured against it (/audit/state-leg-results) and so every era is computed the same way.

export type PresByEraVote = {
  demVotes: number;
  repVotes: number;
  othVotes: number;
  totalVotes: number;
  demPct: number;
  repPct: number;
  /** + = R advantage, share of the full total (matches lib/colorScale.ts). */
  margin: number;
};

export type StateLegPresByEraDistrict = {
  /** 2020 Census population inside the district polygon (DRA T_20_CENS, area-apportioned). */
  pop2020: number;
  /** Share of the district's presidential votes that came through VTDs split by its lines. */
  splitPct: number;
  "2016"?: PresByEraVote;
  "2020"?: PresByEraVote;
  "2024"?: PresByEraVote;
  /** An overlay district (a New Hampshire floterial): the sum of these base districts, current map only. */
  overlayOf?: string[];
};

/** Era key: "current", or the boundary-file vintage as a string ("2020", "2022"). */
export type StateLegPresByEra = Record<string, Record<string, StateLegPresByEraDistrict>>;

// state abbreviation -> chamber -> era -> district key
export const stateLegPresByEra: Record<string, Partial<Record<Chamber, StateLegPresByEra>>> = `;

writeFileSync(OUT_FILE, `${header}${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${OUT_FILE}: ${Object.keys(data).length} states, ${eras} chamber-eras, ${districts} district-eras (${overlays} overlay districts recombined from their base districts)`);
