// Converts electindex historical.csv → data/districtPresidentialData.ts
// Keys output by 4-digit district ID (state_fips + district_num, zero-padded)
// matching the houseStatewideResults convention in forecastData.ts

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const STATE_FIPS = {
  AL: "01", AK: "02", AZ: "04", AR: "05", CA: "06", CO: "08", CT: "09",
  DE: "10", FL: "12", GA: "13", HI: "15", ID: "16", IL: "17", IN: "18",
  IA: "19", KS: "20", KY: "21", LA: "22", ME: "23", MD: "24", MA: "25",
  MI: "26", MN: "27", MS: "28", MO: "29", MT: "30", NE: "31", NV: "32",
  NH: "33", NJ: "34", NM: "35", NY: "36", NC: "37", ND: "38", OH: "39",
  OK: "40", OR: "41", PA: "42", RI: "44", SC: "45", SD: "46", TN: "47",
  TX: "48", UT: "49", VT: "50", VA: "51", WA: "53", WV: "54", WI: "55",
  WY: "56",
};

function toDistrictId(code) {
  // "AL-01" → "0101", "CA-52" → "0652"
  const [state, distStr] = code.split("-");
  const fips = STATE_FIPS[state];
  if (!fips) throw new Error(`Unknown state: ${state}`);
  const dist = distStr.padStart(2, "0");
  return fips + dist;
}

function twoPct(dem, rep) {
  const total = dem + rep;
  return total === 0 ? 0 : (dem / total) * 100;
}

const csvPath = join(__dirname, "../data-entry/electindex_historical.csv");
const raw = readFileSync(csvPath, "utf8");
const lines = raw.trim().split("\n");
const headers = lines[0].split(",");

const rows = lines.slice(1).map(line => {
  const vals = line.split(",");
  return Object.fromEntries(headers.map((h, i) => [h, vals[i]]));
});

// Filter to district-level rows only
const districtRows = rows.filter(r => r.level === "district");

// Build the output map
const entries = districtRows.map(r => {
  const id = toDistrictId(r.code);
  const d16 = parseInt(r.pres16_dem), r16 = parseInt(r.pres16_rep);
  const d20 = parseInt(r.pres20_dem), r20 = parseInt(r.pres20_rep);
  const d24 = parseInt(r.pres24_dem), r24 = parseInt(r.pres24_rep);

  return {
    id,
    code: r.code,
    state: r.state,
    pres16: { demPct: twoPct(d16, r16), repPct: twoPct(r16, d16), demVotes: d16, repVotes: r16 },
    pres20: { demPct: twoPct(d20, r20), repPct: twoPct(r20, d20), demVotes: d20, repVotes: r20 },
    pres24: { demPct: twoPct(d24, r24), repPct: twoPct(r24, d24), demVotes: d24, repVotes: r24 },
  };
});

const round = n => Math.round(n * 10) / 10;

const lines_out = [
  "// Auto-generated by scripts/process-district-presidential.mjs",
  "// Source: electindex.com historical presidential results (2016/2020/2024)",
  "// Reaggregated to current (post-2022) congressional district boundaries.",
  "// Key: 4-digit district ID (state_fips + district_num) matching houseStatewideResults.",
  "",
  "export type DistrictPresResult = {",
  "  code: string;       // e.g. \"AL-01\"",
  "  state: string;      // e.g. \"AL\"",
  "  pres16DemPct: number;",
  "  pres16RepPct: number;",
  "  pres16DemVotes: number;",
  "  pres16RepVotes: number;",
  "  pres20DemPct: number;",
  "  pres20RepPct: number;",
  "  pres20DemVotes: number;",
  "  pres20RepVotes: number;",
  "  pres24DemPct: number;",
  "  pres24RepPct: number;",
  "  pres24DemVotes: number;",
  "  pres24RepVotes: number;",
  "};",
  "",
  "export const districtPresidentialData: Record<string, DistrictPresResult> = {",
  ...entries.map(e =>
    `  "${e.id}": { code: "${e.code}", state: "${e.state}", ` +
    `pres16DemPct: ${round(e.pres16.demPct)}, pres16RepPct: ${round(e.pres16.repPct)}, pres16DemVotes: ${e.pres16.demVotes}, pres16RepVotes: ${e.pres16.repVotes}, ` +
    `pres20DemPct: ${round(e.pres20.demPct)}, pres20RepPct: ${round(e.pres20.repPct)}, pres20DemVotes: ${e.pres20.demVotes}, pres20RepVotes: ${e.pres20.repVotes}, ` +
    `pres24DemPct: ${round(e.pres24.demPct)}, pres24RepPct: ${round(e.pres24.repPct)}, pres24DemVotes: ${e.pres24.demVotes}, pres24RepVotes: ${e.pres24.repVotes} },`
  ),
  "};",
  "",
];

const outPath = join(__dirname, "../data/districtPresidentialData.ts");
writeFileSync(outPath, lines_out.join("\n"), "utf8");
console.log(`Written ${entries.length} districts to ${outPath}`);
