#!/usr/bin/env node
/**
 * Regenerates data/stateLegResults.ts from data-entry/state-leg-results/{ABBR}-{year}.json - the
 * per-district state legislative ELECTION RESULTS (who ran for the legislature and how many votes
 * they got), which is a different quantity from data/stateLegPres2024.ts (presidential votes
 * apportioned into legislative districts).
 *
 * This is the Phase 3 output of the state-leg historical results project. Chamber-years that have
 * not been sourced yet are simply absent - /audit/state-leg-results lists what is present and diffs
 * each chamber-year's district sum against the statewide row in data-entry/state_leg.csv.
 *
 * Each input file is {chamber: {source, note?, districts: {number: {demVotes, repVotes, othVotes,
 * totalVotes}}}}. The `source` string matters beyond provenance: the audit's aggregate check is
 * only meaningful when the districts and the statewide row were sourced independently, so the page
 * compares this string to the statewide row's own `source` and flags a match as shared lineage.
 *
 * Usage: node scripts/build-state-leg-results.mjs
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";

const SRC_DIR = "data-entry/state-leg-results";
const OUT_FILE = "data/stateLegResults.ts";

const files = existsSync(SRC_DIR)
  ? readdirSync(SRC_DIR)
      .filter((f) => /^[A-Z]{2}-\d{4}\.json$/.test(f))
      .sort()
  : [];

// abbr -> year -> chamber -> block
const data = {};
let chamberYears = 0;
let districts = 0;
for (const file of files) {
  const [abbr, year] = file.replace(/\.json$/, "").split("-");
  const parsed = JSON.parse(readFileSync(`${SRC_DIR}/${file}`, "utf8"));
  for (const [chamber, block] of Object.entries(parsed)) {
    ((data[abbr] ??= {})[year] ??= {})[chamber] = block;
    chamberYears += 1;
    districts += Object.keys(block.districts ?? {}).length;
  }
}

const header = `import type { Chamber } from "./stateLegDistricts";

// Per-district state legislative ELECTION results - the legislative race itself, not the
// presidential vote inside the district (that is data/stateLegPres2024.ts). Auto-generated by
// scripts/build-state-leg-results.mjs from data-entry/state-leg-results/{ABBR}-{year}.json - do not
// edit by hand, rerun the build script instead.
//
// Chamber-years that have not been sourced yet are simply absent, and a chamber that IS present can
// still be incomplete. The two sources say so in DIFFERENT ways, and the difference is meaningful:
//
//   * The Klarner pass (2016-2022) lists every district and marks the ones with no published count
//     \`noCount: true\` with null votes - so the district is known to exist and known to be unmeasured.
//   * The MEDSL pass (2024) and the Louisiana file simply OMIT such a district, because those
//     sources carry no row for a race that was never printed. Absence there means "not in the
//     source", which is weaker than Klarner's explicit null.
//
// Either way the chamber sum sits below statewide turnout in states that declare unopposed
// candidates elected. /audit/state-leg-results reports both cases.

export type StateLegDistrictResult = {
  /**
   * Votes cast, or NULL where the district held the seat but no count was ever published.
   * Oklahoma, Florida, Texas and Hawaii declare an unopposed candidate elected without
   * printing the race, so no ballot is cast for that office in that district - null, not
   * zero, which would assert a real 0-0 result. Indiana prints unopposed races and so has a
   * count for every district. Always check \`noCount\` (or a null) before dividing.
   */
  demVotes: number | null;
  repVotes: number | null;
  othVotes: number | null;
  totalVotes: number | null;
  /** True when no vote count exists for this district; all four vote fields are then null. */
  noCount?: boolean;
  /** True when every contest in this district had a single candidate. */
  uncontested?: boolean;
};

export type StateLegChamberResults = {
  /**
   * Where these district figures came from. Compared against the statewide row's source in
   * data-entry/state_leg.csv by the audit page: when the two match, the aggregate-vs-statewide
   * check is comparing a source to itself and proves plumbing rather than accuracy.
   */
  source: string;
  note?: string;
  /** District key matches StateLegDistrict.number, e.g. "12", "12A". */
  districts: Record<string, StateLegDistrictResult>;
};

// state abbreviation -> election year -> chamber
export const stateLegResults: Record<
  string,
  Record<string, Partial<Record<Chamber, StateLegChamberResults>>>
> = `;

writeFileSync(OUT_FILE, `${header}${JSON.stringify(data, null, 1)};\n`);
console.log(
  `wrote ${OUT_FILE}: ${Object.keys(data).length} states, ${chamberYears} chamber-years, ${districts} districts`
);
